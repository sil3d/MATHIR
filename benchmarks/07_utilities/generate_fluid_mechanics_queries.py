#!/usr/bin/env python3
"""
Generate synthetic BEIR-style queries.jsonl + qrels/test.tsv for the
fluid_mechanics dataset built by build_fluid_mechanics_corpus.py.

METHODOLOGY / HONEST LIMITATIONS (read before trusting these numbers):

  - This produces SINGLE-GOLD-PASSAGE relevance judgments, not exhaustively
    annotated qrels. Each query is generated FROM one specific source
    passage, and that one passage is marked relevance=1 in qrels/test.tsv.
    Unlike SciFact (which has real multi-passage, multi-label expert
    annotations), we do NOT check whether other corpus passages might also
    answer the same question. This is the standard, disclosed limitation of
    LLM-generated-from-a-single-source query sets: recall/nDCG here may be
    pessimistic wherever a retriever finds a genuinely relevant passage that
    isn't the literal source paragraph an LLM was shown.

  - Queries are generated by prompting an LLM with ONLY the source passage
    and asking for one self-contained factual question answerable from it.
    Quality depends on the LLM actually following that instruction; a
    fraction of generations may be low quality or fail outright (tracked and
    reported as a failure count, not silently dropped without a trace).

  - Sampling is deterministic (fixed stride across the corpus, proportional
    across both source books) so reruns are reproducible modulo whatever the
    LLM backend returns for a given passage.

Usage:
    python generate_fluid_mechanics_queries.py [--n-samples 280] [--seed 42]

Requires a working LLM backend as configured for
benchmarks/08_industry_validation/llm_client.py (OPENAI_API_KEY/BASE/MODEL
env vars, or MATHIR_API_KEY/MATHIR_API_BASE/MATHIR_API_MODEL in
benchmarks/.env). If no backend is configured, or the backend returns a real
API error (e.g. HTTP 402 insufficient credits), this script does NOT
fabricate query data -- it prints a clear diagnostic and exits nonzero
without touching queries.jsonl/qrels/test.tsv.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "08_industry_validation"))
import llm_client  # noqa: E402

CORPUS_DIR = (
    Path(__file__).resolve().parent.parent
    / "05_test_data"
    / "beir_data"
    / "fluid_mechanics"
    / "fluid_mechanics"
)
CORPUS_FILE = CORPUS_DIR / "corpus.jsonl"
QUERIES_FILE = CORPUS_DIR / "queries.jsonl"
QRELS_DIR = CORPUS_DIR / "qrels"
QRELS_FILE = QRELS_DIR / "test.tsv"

PROMPT_TEMPLATE = (
    "You are creating a test question for an information-retrieval benchmark. "
    "Given ONLY this passage from a fluid mechanics textbook, write ONE specific, "
    "self-contained factual question whose answer can be found in this passage. "
    "The question must make sense on its own without seeing the passage (don't say "
    "'according to this passage' or similar). Do not include the answer. Return ONLY "
    "the question text, nothing else.\n\nPassage:\n{text}"
)


def check_llm_backend() -> bool:
    print("Checking LLM backend connectivity...")
    try:
        reply = llm_client.chat(
            [{"role": "user", "content": "Reply with exactly one word: OK"}],
            max_tokens=10,
        )
        print(f"  Backend responded: {reply!r}")
        return True
    except Exception as e:
        print(f"  Backend check FAILED: {e}")
        return False


def load_corpus() -> list[dict]:
    docs = []
    with open(CORPUS_FILE, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                docs.append(json.loads(line))
    return docs


def sample_docs(docs: list[dict], n_samples: int, seed: int) -> list[dict]:
    """Deterministic proportional sample across both books via fixed stride."""
    by_book: dict[str, list[dict]] = {}
    for d in docs:
        book = d["_id"].split("_")[0]
        by_book.setdefault(book, []).append(d)

    total = len(docs)
    sampled = []
    for book, book_docs in by_book.items():
        book_docs_sorted = sorted(book_docs, key=lambda d: d["_id"])
        n_for_book = max(1, round(n_samples * len(book_docs) / total))
        stride = max(1, len(book_docs_sorted) // n_for_book)
        chosen = book_docs_sorted[::stride][:n_for_book]
        sampled.extend(chosen)
        print(f"  {book}: {len(chosen)} sampled from {len(book_docs)} chunks (stride {stride})")
    return sampled


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n-samples", type=int, default=280)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    if not CORPUS_FILE.exists():
        print(f"ERROR: corpus not found at {CORPUS_FILE}. Run build_fluid_mechanics_corpus.py first.")
        sys.exit(1)

    if not check_llm_backend():
        print(
            "\nERROR: no working LLM backend. Query generation NOT run. "
            "No queries.jsonl/qrels were written or modified.\n"
            "To fix: configure a real, funded API key -- either set "
            "OPENAI_API_KEY/OPENAI_BASE_URL/OPENAI_MODEL in the shell environment, "
            "or MATHIR_API_KEY/MATHIR_API_BASE/MATHIR_API_MODEL in benchmarks/.env "
            "(see benchmarks/.env.example) -- then re-run this script."
        )
        sys.exit(2)

    print("Loading corpus...")
    docs = load_corpus()
    print(f"  {len(docs)} chunks loaded from {CORPUS_FILE}")

    print(f"\nSampling ~{args.n_samples} passages proportionally across books...")
    sampled = sample_docs(docs, args.n_samples, args.seed)
    print(f"  Total sampled: {len(sampled)}")

    queries = []
    qrels_rows = []
    failures = 0
    examples = []

    for i, doc in enumerate(sampled):
        qid = str(i + 1)
        prompt = PROMPT_TEMPLATE.format(text=doc["text"])
        try:
            question = llm_client.chat(
                [{"role": "user", "content": prompt}],
                max_tokens=200,
                temperature=0.3,
            ).strip()
            if not question:
                raise ValueError("empty response")
        except Exception as e:
            failures += 1
            print(f"  [{i+1}/{len(sampled)}] FAILED for {doc['_id']}: {e}")
            continue

        queries.append({"_id": qid, "text": question, "metadata": {}})
        qrels_rows.append((qid, doc["_id"], 1))
        if len(examples) < 5:
            examples.append((question, doc["_id"]))
        if (i + 1) % 25 == 0:
            print(f"  [{i+1}/{len(sampled)}] generated so far, {failures} failures")

    print(f"\nDone. Generated {len(queries)} queries, {failures} failures out of {len(sampled)} attempted.")

    if not queries:
        print("ERROR: zero queries generated successfully. Not writing any files.")
        sys.exit(3)

    QRELS_DIR.mkdir(parents=True, exist_ok=True)
    with open(QUERIES_FILE, "w", encoding="utf-8") as f:
        for q in queries:
            f.write(json.dumps(q, ensure_ascii=False) + "\n")
    with open(QRELS_FILE, "w", encoding="utf-8") as f:
        f.write("query-id\tcorpus-id\tscore\n")
        for qid, cid, score in qrels_rows:
            f.write(f"{qid}\t{cid}\t{score}\n")

    print(f"Wrote {len(queries)} queries to {QUERIES_FILE}")
    print(f"Wrote {len(qrels_rows)} qrels rows to {QRELS_FILE}")

    print("\n=== Example generated questions ===")
    for question, source_id in examples:
        print(f"  [{source_id}] {question}")


if __name__ == "__main__":
    main()
